"""Emit current/policy_data.h from a trained policy checkpoint.

Tables: POLICY_W[729] (per-window contribution), POLICY_C[8549] (conjunction
class; index 8548 = no-class fallback), plus color-mirror index tables
(root-relative pattern digits -> opponent's perspective).

    python emit_policy.py                # from output_policy/policy.pt
    python emit_policy.py --zero         # zero tables (compile testing)
"""

import argparse
import os

import numpy as np

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
CURRENT = os.path.join(SCRIPT_DIR, "..", "..", "current")
NUM_CLASSES = 8548


def flit(v):
    s = f"{v:.6g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default=os.path.join(SCRIPT_DIR, "output_policy",
                                                   "policy.pt"))
    ap.add_argument("--zero", action="store_true")
    ap.add_argument("--out", default=os.path.join(CURRENT, "policy_data.h"))
    args = ap.parse_args()

    if args.zero:
        pw = np.zeros(729, dtype=np.float32)
        pc = np.zeros(NUM_CLASSES + 1, dtype=np.float32)
    else:
        import torch
        d = torch.load(args.ckpt, map_location="cpu")
        pw = d["pw"].numpy().astype(np.float32)
        pc = d["pc"].numpy().astype(np.float32)
        assert pw.shape == (729,) and pc.shape == (NUM_CLASSES + 1,)

    cb = np.load(os.path.join(SCRIPT_DIR, "..", "nnue", "codebook.npz"))
    mir729 = cb["mirror729"].astype(np.int64)
    cmir = cb["class_mirror"].astype(np.int64)

    with open(args.out, "w") as f:
        f.write("// Generated by emit_policy.py -- do not edit.\n"
                "#pragma once\n#include <cstdint>\n\n")
        f.write(f"static const float POLICY_W[729] = {{"
                + ",".join(flit(v) for v in pw) + "};\n")
        f.write(f"static const float POLICY_C[{NUM_CLASSES + 1}] = {{"
                + ",".join(flit(v) for v in pc) + "};\n")
        f.write("static const uint16_t POLICY_MIR_W[729] = {"
                + ",".join(str(int(v)) for v in mir729) + "};\n")
        f.write(f"static const uint16_t POLICY_MIR_C[{NUM_CLASSES}] = {{"
                + ",".join(str(int(v)) for v in cmir) + "};\n")
    print(f"wrote {args.out} ({os.path.getsize(args.out)/1e6:.1f} MB)"
          + (" [ZERO]" if args.zero else ""))


if __name__ == "__main__":
    main()
