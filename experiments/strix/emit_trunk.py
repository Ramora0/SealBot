"""Emit trunk v1.2 (mirror-trained Trunk2) into the engine.

Writes:
  current/trunk_data.h   — small arrays (EW bag, value head, policy head)
  current/trunk_eraw.bin — E_raw[3^11 x K] float32 raw blob (~22.7 MB;
                           loaded at runtime, too big for a header)

Scale convention: training targets are strix_v * 8 in net units; engine
scores are strix_v * 8000 -> OUT_SCALE = 1000 (same as net_data.h).

    python emit_trunk.py --ckpt output_trunk2m/trunk.pt
"""

import argparse
import os

import numpy as np
import torch

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SEAL = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
CUR = os.path.join(SEAL, "current")


def fmt(arr, per_line=8):
    flat = np.asarray(arr, dtype=np.float64).ravel()
    parts = [f"{v:.8g}f" for v in flat]
    lines = [",".join(parts[i:i + per_line])
             for i in range(0, len(parts), per_line)]
    return ",\n".join(lines)


def emit_2d(name, a):
    rows = [f"{{{','.join(f'{v:.8g}f' for v in row)}}}" for row in a]
    return (f"static const float {name}[{a.shape[0]}][{a.shape[1]}] = {{\n"
            + ",\n".join(rows) + "};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default=os.path.join(SCRIPT_DIR, "output_trunk2m",
                                                   "trunk.pt"))
    ap.add_argument("--blend", type=float, default=0.15)
    args = ap.parse_args()

    ck = torch.load(args.ckpt, map_location="cpu")
    sd = ck["state"]
    K, H, HP, CLIP = ck["K"], ck["H"], ck["HP"], ck["CLIP"]
    assert ck.get("arch") == "v2", "expected Trunk2 checkpoint"

    eraw = sd["eraw.weight"].numpy().astype(np.float32)      # [3^11, K]
    ew = sd["ew.weight"].numpy().astype(np.float32)          # [729, K]
    w1 = sd["w1.weight"].numpy(); b1 = sd["w1.bias"].numpy()  # [H, K+2]
    w2 = sd["w2.weight"].numpy().ravel(); b2 = float(sd["w2.bias"].numpy()[0])
    p1 = sd["p1.weight"].numpy(); p1b = sd["p1.bias"].numpy()  # [HP, 2K+2]
    p2 = sd["p2.weight"].numpy().ravel(); p2b = float(sd["p2.bias"].numpy()[0])

    blob_path = os.path.join(CUR, "trunk_eraw.bin")
    eraw.tofile(blob_path)
    print(f"wrote {blob_path} ({eraw.nbytes/1e6:.1f} MB)")

    hdr = ["// Generated by emit_trunk.py -- do not edit.", "#pragma once", ""]
    hdr.append(f"static constexpr int TRK_K = {K};")
    hdr.append(f"static constexpr int TRK_H = {H};")
    hdr.append(f"static constexpr int TRK_HP = {HP};")
    hdr.append(f"static const float TRK_CLIP = {CLIP}f;")
    hdr.append("static const float TRK_OUT_SCALE = 1000.0f;")
    hdr.append(f"static const float TRK_LIN_BLEND = {args.blend}f;")
    hdr.append(f"static const float TRK_B2 = {b2:.8g}f;")
    hdr.append(f"static const float TRK_P2B = {p2b:.8g}f;")
    hdr.append(f'static const char* TRK_ERAW_PATH = "{blob_path}";')
    hdr.append(f"static constexpr long TRK_ERAW_ROWS = {eraw.shape[0]}L;")
    hdr.append("")
    hdr.append(emit_2d("TRK_EW", ew))
    hdr.append(emit_2d("TRK_W1", w1))
    hdr.append(f"static const float TRK_B1[{H}] = {{{fmt(b1)}}};\n")
    hdr.append(f"static const float TRK_W2[{H}] = {{{fmt(w2)}}};\n")
    hdr.append(emit_2d("TRK_P1", p1))
    hdr.append(f"static const float TRK_P1B[{HP}] = {{{fmt(p1b)}}};\n")
    hdr.append(f"static const float TRK_P2[{HP}] = {{{fmt(p2)}}};\n")

    out = os.path.join(CUR, "trunk_data.h")
    with open(out, "w") as fh:
        fh.write("\n".join(hdr))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
