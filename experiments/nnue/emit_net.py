"""Emit net_data.h for the engine from a trained checkpoint (or random init).

Usage:
    python emit_net.py --random             # bootstrap header (compile/testing)
    python emit_net.py --ckpt output/net.pt # from trained checkpoint
"""

import argparse
import os

import numpy as np

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
CURRENT_DIR = os.path.join(ROOT_DIR, "current")

K, H, G = 32, 32, 2
NUM_CLASSES = 8548
OUT_SCALE = 600.0
CLIP = 8.0


def flit(v):
    s = f"{v:.7g}"
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def fmt_2d(name, arr):
    rows = []
    for row in arr:
        rows.append("{" + ",".join(flit(v) for v in row) + "}")
    return (f"static const float {name}[{arr.shape[0]}][{arr.shape[1]}] = "
            "{" + ",".join(rows) + "};\n")


def fmt_1d(name, arr):
    return (f"static const float {name}[{len(arr)}] = "
            "{" + ",".join(flit(v) for v in arr) + "};\n")


def emit(ew, ec, w1, b1, w2, b2, out_path, out_scale=OUT_SCALE, clip=CLIP,
         lin_blend=0.0):
    assert ew.shape == (729, K) and ec.shape == (NUM_CLASSES, K)
    assert w1.shape == (H, K + G) and b1.shape == (H,) and w2.shape == (H,)
    with open(out_path, "w") as f:
        f.write("// Generated by emit_net.py -- do not edit.\n#pragma once\n\n")
        f.write(f"static constexpr int NET_K = {K};\n")
        f.write(f"static constexpr int NET_H = {H};\n")
        f.write(f"static constexpr int NET_G = {G};\n")
        f.write(f"static const float NET_OUT_SCALE = {flit(out_scale)};\n")
        f.write(f"static const float NET_CLIP = {flit(clip)};\n")
        f.write(f"static const float NET_LIN_BLEND = {flit(lin_blend)};\n")
        f.write(f"static const float NET_B2 = {flit(float(b2))};\n\n")
        f.write(fmt_2d("NET_EW", ew))
        f.write(fmt_2d("NET_EC", ec))
        f.write(fmt_2d("NET_W1", w1))
        f.write(fmt_1d("NET_B1", b1))
        f.write(fmt_1d("NET_W2", w2))
    np.savez(out_path + ".npz", ew=ew, ec=ec, w1=w1, b1=b1, w2=w2,
             b2=np.float32(b2), out_scale=np.float32(out_scale),
             clip=np.float32(clip), lin_blend=np.float32(lin_blend))
    print(f"wrote {out_path} ({os.path.getsize(out_path)/1e6:.1f} MB) + sidecar npz")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--random", action="store_true")
    ap.add_argument("--ckpt", type=str, default=None)
    ap.add_argument("--lin-blend", type=float, default=0.0,
                    help="engine adds lin_blend * old linear eval to net out")
    ap.add_argument("--out", type=str,
                    default=os.path.join(CURRENT_DIR, "net_data.h"))
    args = ap.parse_args()

    if args.random:
        rng = np.random.default_rng(7)
        emit(rng.normal(0, 0.02, (729, K)).astype(np.float32),
             rng.normal(0, 0.02, (NUM_CLASSES, K)).astype(np.float32),
             rng.normal(0, 0.1, (H, K + G)).astype(np.float32),
             np.zeros(H, dtype=np.float32),
             rng.normal(0, 0.1, H).astype(np.float32),
             0.0, args.out)
    else:
        import torch
        sd = torch.load(args.ckpt, map_location="cpu")
        emit(sd["ew.weight"].numpy(),
             sd["ec.weight"].numpy(),
             sd["w1.weight"].numpy(),
             sd["w1.bias"].numpy(),
             sd["w2.weight"].numpy().reshape(-1),
             float(sd["w2.bias"].numpy().reshape(-1)[0]),
             args.out,
             out_scale=float(sd.get("out_scale", OUT_SCALE)),
             clip=float(sd.get("clip", CLIP)),
             lin_blend=args.lin_blend)


if __name__ == "__main__":
    main()
